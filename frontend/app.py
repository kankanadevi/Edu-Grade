import streamlit as st
import requests
import os

st.set_page_config(page_title="EduGrade | Student Performance & At-Risk Intervention", page_icon="📚", layout="wide")

st.title("EduGrade: Student Performance & At-Risk Intervention System")
st.markdown("Early academic support and intervention dashboard based on the UCI Student Performance Dataset.")

API_BASE = os.environ.get("EDUGRADE_API_URL", "http://127.0.0.1:8000")

with st.sidebar:
    st.header("Service Settings")
    api_url = st.text_input("Backend API URL", value=API_BASE)
    st.info("Ensure the FastAPI backend is running on Render or locally.")

with st.form("student_form"):
    st.subheader("Student Academic & Demographic Intake (FR-07)")
    col1, col2 = st.columns(2)
    
    with col1:
        studytime = st.selectbox("Weekly Study Time", [1, 2, 3, 4], index=1, format_func=lambda x: f"{x} ({['<2h','2-5h','5-10h','>10h'][x-1]})")
        absences = st.number_input("Absences Count", min_value=0, max_value=93, value=4)
        failures = st.number_input("Past Failures", min_value=0, max_value=4, value=0)
        age = st.number_input("Age", min_value=15, max_value=22, value=17)
        Medu = st.selectbox("Mother's Education", [0,1,2,3,4], index=2, format_func=lambda x: ["None","Primary (4th)","5th-9th","Secondary","Higher"][x])
        Fedu = st.selectbox("Father's Education", [0,1,2,3,4], index=2, format_func=lambda x: ["None","Primary (4th)","5th-9th","Secondary","Higher"][x])
    
    with col2:
        schoolsup = st.selectbox("School Support", [0,1], format_func=lambda x: "Yes" if x else "No")
        famsup = st.selectbox("Family Support", [0,1], index=1, format_func=lambda x: "Yes" if x else "No")
        paid = st.selectbox("Paid Classes", [0,1], format_func=lambda x: "Yes" if x else "No")
        activities = st.selectbox("Activities", [0,1], format_func=lambda x: "Yes" if x else "No")
        internet = st.selectbox("Internet", [0,1], index=1, format_func=lambda x: "Yes" if x else "No")
        higher = st.selectbox("Wants Higher Education", [0,1], index=1, format_func=lambda x: "Yes" if x else "No")
        First_Term = st.number_input("First Term Grade (0-20)", min_value=0, max_value=20, value=12)
        Second_Term = st.number_input("Second Term Grade (0-20)", min_value=0, max_value=20, value=12)
    
    submitted = st.form_submit_button("Run Prediction & Risk Analysis")

if submitted:
    payload = {
        "studytime": studytime,
        "absences": absences,
        "failures": failures,
        "age": age,
        "schoolsup": schoolsup,
        "famsup": famsup,
        "paid": paid,
        "activities": activities,
        "internet": internet,
        "higher": higher,
        "Medu": Medu,
        "Fedu": Fedu,
        "First_Term": First_Term,
        "Second_Term": Second_Term
    }
    
    endpoint = api_url.rstrip("/") + "/predict"
    try:
        response = requests.post(endpoint, json=payload, timeout=5)
        if response.status_code == 200:
            result = response.json()
            st.success("Prediction Successfully Generated by " + result.get("model_used", "Linear SVC Pipeline"))
            
            c1, c2 = st.columns(2)
            with c1:
                st.metric("Predicted Final Grade Band", result.get("predicted_grade_band"))
            with c2:
                st.metric("Academic Risk Level", result.get("risk_level"))
                
            if "risk_factors" in result and result["risk_factors"]:
                st.subheader("Decision Factors")
                for factor in result["risk_factors"]:
                    st.write(f"- {factor}")
            
            if "recommendation" in result:
                st.info(f"Recommended Action: {result['recommendation']}")
        else:
            st.error(f"API Error ({response.status_code}): {response.text}")
    except Exception as e:
        st.error(f"Could not connect to FastAPI server at {endpoint}: {e}")
